# ============ 十神 ============
# 相对日干：比肩/劫财(同我), 食神/伤官(我生), 正财/偏财(我克),
# 正官/七杀(克我), 正印/偏印(生我)
TEN_GOD = ["比肩", "劫财", "食神", "伤官", "正财", "偏财", "正官", "七杀", "正印", "偏印"]


def ten_god(day_gan: str, other_gan: str) -> str:
    """计算 other_gan 相对 day_gan 的十神。"""
    dw = GAN_ELEMENT[GAN_INDEX[day_gan]]
    dy = GAN_YINYANG[GAN_INDEX[day_gan]]
    ow = GAN_ELEMENT[GAN_INDEX[other_gan]]
    oy = GAN_YINYANG[GAN_INDEX[other_gan]]
    if ow == dw:  # 比劫
        return "比肩" if oy == dy else "劫财"
    if SHENG[ow] == dw:  # 生我 -> 印
        return "正印" if oy != dy else "偏印"
    if SHENG[dw] == ow:  # 我生 -> 食伤
        return "食神" if oy == dy else "伤官"
    if KE[ow] == dw:  # 克我 -> 官杀
        return "正官" if oy != dy else "七杀"
    if KE[dw] == ow:  # 我克 -> 财
        return "偏财" if oy == dy else "正财"
    return "?"


